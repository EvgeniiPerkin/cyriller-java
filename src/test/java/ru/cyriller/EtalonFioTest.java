    @ParameterizedTest(name = "{0}")
    @MethodSource("fioData")
    void testEtalonFio(Fio fio) {
        Cases[] cases = Cases.values();
        for (int i = 0; i < cases.length; i++) {
            CyrNameResult r = cyrName.decline(fio.surname(), fio.name(), fio.patronymic(),
                    cases[i], fio.gender(), false);
            assertEquals(fio.surnameCases()[i], r.surname(),
                    "фамилия, " + cases[i] + ": " + fio);
            assertEquals(fio.nameCases()[i], r.name(),
                    "имя, " + cases[i] + ": " + fio);
            assertEquals(fio.patronymicCases()[i], r.patronymic(),
                    "отчество, " + cases[i] + ": " + fio);
        }
    }
